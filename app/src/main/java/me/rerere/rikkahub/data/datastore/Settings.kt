    // 网页端口映射：只有列在这里的端口能被 /p/{port}/ 代理
    val webServerPortMappings: List<WebServerPortMapping> = emptyList(),
    val backupReminderConfig: BackupReminderConfig = BackupReminderConfig(),
    // 终端会话热池: 预热好的 proot shell 让新标签页/下一条 AI 命令免去 1~3 秒冷启动。
    // 0 表示关闭。界面属于终端设置族(WP8/4.7), 现在先靠默认值生效。
    val terminalPrewarmSessions: Int = 1,
    val terminalPrewarmIdleMinutes: Int = 5,
    // 设备控制: 打开后会改动设备的动作(点击/滑动/输入/按键/打开应用)不再逐次请求确认。
    // 默认关(安全优先), 用户可在设备控制状态卡里放开。
    val deviceAgentAutoApprove: Boolean = false,
    // 对话页顶栏是否显示设备控制三色灯。
    val deviceControlShowIndicator: Boolean = true,

    // 模型价格覆盖：用户按实际账单声明的价格，统计计价时优先于内置参考表
    val modelPriceOverrides: List<PriceOverride> = emptyList(),

    /** 启动页：home＝主页；terminal＝直接打开 Linux 终端（第一个工作区） */
    val startupTarget: String = "home",
) {
    companion object {
        // 构造一个用于初始化的settings, 但它不能用于保存，防止使用初始值存储
        fun dummy() = Settings(init = true)
    }
}

@Serializable
data class NetworkSetting(
    val userAgent: String = "",
    val proxyUrl: String = "",
    val proxyUsername: String = "",
    val proxyPassword: String = "",
    val enableAutoRetry: Boolean = true,
)

/**
 * 网页端口映射：把设备上 127.0.0.1 的某个服务（code-server、Jupyter、noVNC……）
 * 通过内置 WebServer 的 `/p/{port}/` 暴露出去。
 *
 * 只有列在这里的端口才允许被代理，避免 WebServer 变成任意本地端口扫描器。
 */
@Serializable
data class WebServerPortMapping(
    val name: String = "",
    val port: Int = 0,
    val enabled: Boolean = true,
)

